/**
 * Shopping assistant chatbot. When an LLM is configured (llm.enabled=true,
 * works with OpenAI-style or a local Ollama server) the reply is generated by
 * a Spring AI {@link ChatClient} that can call {@link ShoppingAssistantTools}
 * (@Tool-annotated methods) to search the catalogue, pull trending/personalized
 * picks, similar/frequently-bought-together products, review sentiment/reviews,
 * the shopper's own orders/tracking/cancellation/returns/refunds, cart, wishlist,
 * notifications, profile and store policy info — the model decides which tool(s)
 * to call, instead of hand-rolled keyword extraction. If the LLM is disabled/
 * unreachable, a deterministic offline
 * rule-engine (reusing the same catalogue lookups) answers instead.
 */
@Service
public class ChatbotServiceImpl implements ChatbotService {

    private static final Logger log = LoggerFactory.getLogger(ChatbotServiceImpl.class);

    private static final String SYSTEM_PROMPT = "You are LoomNest's friendly shopping assistant. Answer briefly. "
            + "Use the available tools to look up real data instead of guessing — the product catalogue, "
            + "trending/personalized picks, similar and frequently-bought-together products, review sentiment "
            + "and real reviews, the shopper's own orders/tracking/cancellation/returns/refunds, their own "
            + "cart and wishlist (and adding items to either), their own notifications, their own basic "
            + "account/profile info, and general store policy questions (payment methods, cancellation, "
            + "returns, refunds, tracking). When a shopper wants to return or get a refund, first call the "
            + "draft tool and show them the draft, submit only after they confirm; if you can't resolve their "
            + "problem or they ask for a human, escalate to human support. For a specific question about one product's features, specs or what "
            + "reviewers say, use the product question tool and relay only its answer. "
            + "Never invent product names, prices, order details, or policy facts. "
            + "Only state information a tool call actually returned. "
            + "Never mention tools, function calls, or how you looked something up — speak naturally as if you "
            + "just know the answer, the same way a human store assistant would.";

    private static final Pattern PRICE_PATTERN = Pattern.compile("(\\d+(?:\\.\\d+)?)");

    // common typos/slang/shorthand normalized before keyword extraction, so "gud eraser" -> "good eraser"
    private static final Map<String, String> SYNONYMS = Map.ofEntries(
            Map.entry("gud", "good"),
            Map.entry("rubber", "eraser"),
            Map.entry("mobil", "mobile"),
            Map.entry("lappy", "laptop"),
            Map.entry("pencl", "pencil"),
            Map.entry("notebok", "notebook"));

    // generic/intent words stripped out so only the real product term is used for DB search
    private static final Set<String> STOPWORDS = Set.of(
            "recommend", "suggest", "suggestion", "trending", "popular", "best", "for", "me", "please",
            "want", "need", "looking", "show", "find", "budget", "under", "below", "less", "than", "within",
            "product", "products", "item", "items", "and", "the", "good", "nice", "quality", "some");

    private final ProductClient productClient;
    private final RecommendationService recommendationService;
    private final SentimentService sentimentService;
    private final ReviewSummaryService reviewSummaryService;
    private final ReviewCacheService reviewCache;
    private final OrderClient orderClient;
    private final SellerOrderClient sellerOrderClient;
    private final RefundClient refundClient;
    private final CartClient cartClient;
    private final WishlistClient wishlistClient;
    private final NotificationClient notificationClient;
    private final UserClient userClient;
    private final InternalNotifier internalNotifier;
    private final ProductQaService productQaService;
    private final PolicyKnowledgeService policyKnowledge;
    private final LlmProperties llmProperties;
    // Built once and reused: ChatClient is stateless/thread-safe, so rebuilding it from the
    // Builder on every single chat message (the old behaviour) was pure per-request overhead.
    private final ChatClient chatClient;

    public ChatbotServiceImpl(ProductClient productClient, RecommendationService recommendationService,
            SentimentService sentimentService, ReviewSummaryService reviewSummaryService, ReviewCacheService reviewCache,
            OrderClient orderClient, SellerOrderClient sellerOrderClient, RefundClient refundClient, CartClient cartClient,
            WishlistClient wishlistClient, NotificationClient notificationClient, UserClient userClient,
            InternalNotifier internalNotifier, ProductQaService productQaService, PolicyKnowledgeService policyKnowledge,
            LlmProperties llmProperties, ChatClient.Builder chatClientBuilder) {
        this.productClient = productClient;
        this.recommendationService = recommendationService;
        this.sentimentService = sentimentService;
        this.reviewSummaryService = reviewSummaryService;
        this.reviewCache = reviewCache;
        this.orderClient = orderClient;
        this.sellerOrderClient = sellerOrderClient;
        this.refundClient = refundClient;
        this.cartClient = cartClient;
        this.wishlistClient = wishlistClient;
        this.notificationClient = notificationClient;
        this.userClient = userClient;
        this.internalNotifier = internalNotifier;
        this.productQaService = productQaService;
        this.policyKnowledge = policyKnowledge;
        this.llmProperties = llmProperties;
        this.chatClient = chatClientBuilder.build();
    }

    @Override
    public ChatResponseDTO chat(String message, String language, UUID userId, String authHeader) {
        String normalized = normalize(message);
        if (llmProperties.isEnabled()) {
            ShoppingAssistantTools tools = newTools(userId, authHeader, products -> { });
            try {
                String reply = chatClient
                        .prompt()
                        .system(SYSTEM_PROMPT + LanguageSupport.directive(language))
                        .user(message)
                        .advisors(a -> a.param(ChatMemory.CONVERSATION_ID, conversationId(userId)))
                        .tools(tools)
                        .call()
                        .content();
                if (reply != null && !reply.isBlank()) {
                    return new ChatResponseDTO(reply.trim(), "llm", tools.accumulatedProducts());
                }
            } catch (Exception ex) {
                log.warn("LLM chat call failed, falling back to rule-based engine: {}", ex.getMessage());
            }
        }
        List<ProductResponseDTO> matches = resolveProductsOffline(normalized, userId, authHeader);
        return new ChatResponseDTO(buildRuleReply(normalized, matches), "rule-engine", matches);
    }

    @Override
    public Disposable chatStream(String message, String language, UUID userId, String authHeader, Consumer<String> onToken,
            Consumer<List<ProductResponseDTO>> onProducts, Runnable onDone) {
        String normalized = normalize(message);
        if (llmProperties.isEnabled()) {
            ShoppingAssistantTools tools = newTools(userId, authHeader, onProducts);
            AtomicBoolean received = new AtomicBoolean(false);
            try {
                return chatClient
                        .prompt()
                        .system(SYSTEM_PROMPT + LanguageSupport.directive(language))
                        .user(message)
                        .advisors(a -> a.param(ChatMemory.CONVERSATION_ID, conversationId(userId)))
                        .tools(tools)
                        .stream()
                        .content()
                        .doOnNext(chunk -> {
                            if (chunk != null && !chunk.isEmpty()) {
                                received.set(true);
                                onToken.accept(chunk);
                            }
                        })
                        .doOnError(ex -> log.warn("LLM streaming call failed: {}", ex.getMessage()))
                        .doFinally(signal -> {
                            if (!received.get()) {
                                List<ProductResponseDTO> matches = tools.accumulatedProducts().isEmpty()
                                        ? resolveProductsOffline(normalized, userId, authHeader)
                                        : tools.accumulatedProducts();
                                onProducts.accept(matches);
                                onToken.accept(buildRuleReply(normalized, matches));
                            }
                            onDone.run();
                        })
                        .subscribe();
            } catch (Exception ex) {
                log.warn("LLM streaming call failed, falling back to rule-based engine: {}", ex.getMessage());
            }
        }
        // no LLM (or it failed synchronously) — emit the rule-based reply as a single chunk
        List<ProductResponseDTO> matches = resolveProductsOffline(normalized, userId, authHeader);
        onProducts.accept(matches);
        onToken.accept(buildRuleReply(normalized, matches));
        onDone.run();
        return Disposables.disposed();
    }

    private ShoppingAssistantTools newTools(UUID userId, String authHeader, Consumer<List<ProductResponseDTO>> onProducts) {
        return new ShoppingAssistantTools(productClient, recommendationService, sentimentService, reviewSummaryService,
                reviewCache, orderClient, sellerOrderClient, refundClient, cartClient, wishlistClient, notificationClient,
                userClient, internalNotifier, productQaService, policyKnowledge, userId, authHeader, onProducts);
    }

    private String normalize(String message) {
        return message == null ? "" : message.toLowerCase().trim();
    }

    /**
     * Keys the chat memory per shopper so follow-ups ("show me cheaper ones", "track that
     * order") resolve against their own prior turns, not another user's or no history at all.
     */
    private String conversationId(UUID userId) {
        return userId != null ? userId.toString() : ChatMemory.DEFAULT_CONVERSATION_ID;
    }

    /** Deterministic offline fallback — same catalogue lookups as the @Tool methods, no LLM involved. */
    private List<ProductResponseDTO> resolveProductsOffline(String message, UUID userId, String authHeader) {
        if (message.contains("recommend") || message.contains("suggest") || message.contains("for me")) {
            if (userId != null) {
                List<ProductResponseDTO> personalized = recommendationService.findForUser(userId, authHeader, 5);
                if (!personalized.isEmpty()) {
                    return personalized;
                }
            }
            return recommendationService.findTrendingProducts(5);
        }

        if (message.contains("trending") || message.contains("popular") || message.contains("best")) {
            return recommendationService.findTrendingProducts(5);
        }

        BigDecimal budget = extractBudget(message);
        List<String> keywords = extractKeywords(message);
        if (keywords.isEmpty() && budget == null) {
            // greeting/blank message — nothing to search for, skip the DB round-trip entirely
            return List.of();
        }

        String primaryKeyword = keywords.isEmpty() ? null
                : keywords.stream().max(Comparator.comparingInt(String::length)).get();
        List<ProductResponseDTO> results = searchProducts(primaryKeyword, budget);

        // fall back to OR-across-keywords if the longest-word pick didn't match anything
        if (results.isEmpty() && keywords.size() > 1) {
            Map<UUID, ProductResponseDTO> merged = new LinkedHashMap<>();
            for (String keyword : keywords) {
                if (keyword.equals(primaryKeyword) || merged.size() >= 5) {
                    continue;
                }
                for (ProductResponseDTO product : searchProducts(keyword, budget)) {
                    merged.putIfAbsent(product.getId(), product);
                    if (merged.size() >= 5) {
                        break;
                    }
                }
            }
            if (!merged.isEmpty()) {
                results = new ArrayList<>(merged.values());
            }
        }

        // keyword+budget combo matched nothing — relax to budget-only
        if (results.isEmpty() && primaryKeyword != null && budget != null) {
            results = searchProducts(null, budget);
        }
        return results;
    }

    private List<ProductResponseDTO> searchProducts(String keyword, BigDecimal maxPrice) {
        try {
            log.info("Calling {} service -> searchProducts(keyword={}, maxPrice={})", "msvc-products", keyword, maxPrice);
            ProductSearchPageDTO page = productClient.searchProducts(keyword, maxPrice, 0, 5);
            List<ProductResponseDTO> content = page != null ? page.getContent() : null;
            List<ProductResponseDTO> result = content != null ? content : List.of();
            log.info("searchProducts (rule-engine) returning {} product(s)", result.size());
            return result;
        } catch (Exception ex) {
            log.warn("searchProducts (rule-engine) call failed: {}", ex.getMessage());
            return List.of();
        }
    }

    private List<String> extractKeywords(String message) {
        return Arrays.stream(message.split("\\W+"))
                .map(w -> SYNONYMS.getOrDefault(w, w))
                .filter(w -> w.length() > 2 && !STOPWORDS.contains(w))
                .distinct()
                .limit(5)
                .collect(Collectors.toList());
    }

    private String buildRuleReply(String message, List<ProductResponseDTO> matches) {
        if (message.isBlank()) {
            return "Vanakkam! Naan LoomNest shopping assistant. Enna venum nu sollunga — "
                    + "product name, category, illa budget sollunga, naan suggest panren.";
        }
        if (message.contains("hi") || message.contains("hello") || message.contains("vanakkam")) {
            return "Vanakkam! Enna shopping help venum? Product, category illa budget sollunga.";
        }
        if (matches.isEmpty()) {
            return "Sorry, athukku match aagura product kidaikla. Vera keyword illa budget try pannunga.";
        }
        String list = matches.stream()
                .map(p -> p.getName() + " (₹" + p.getPrice() + ")")
                .collect(Collectors.joining(", "));
        return "Ithu unga ku pidikkalam: " + list + ". Detail venumna product page paarunga!";
    }

    private BigDecimal extractBudget(String message) {
        if (!(message.contains("under") || message.contains("below") || message.contains("budget")
                || message.contains("less than") || message.contains("within"))) {
            return null;
        }
        Matcher matcher = PRICE_PATTERN.matcher(message);
        if (matcher.find()) {
            try {
                return new BigDecimal(matcher.group(1));
            } catch (NumberFormatException ignored) {
                return null;
            }
        }
        return null;
    }
}
